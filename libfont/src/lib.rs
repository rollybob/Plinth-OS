//! An 8x8 bitmap font: glyph rows and the cell size, and nothing else.
//!
//! This is deliberately the smallest possible crate. It exists because the same
//! glyphs are needed on both sides of the kernel boundary -- `libgfx` renders
//! text for library OSes, and the kernel's diagnostic console (real_hardware.md
//! D11) renders text on a machine with no serial port -- and two copies of a
//! font would be one decision written in two places.
//!
//! **What is shared is data, not policy, and the distinction is the whole point
//! of the split.** This crate answers "which pixels make the letter A". It does
//! not decide where text goes, what colour it is, how lines wrap, when to
//! scroll, or what a cursor looks like. Those are the interesting decisions and
//! they stay with whoever is drawing: `libgfx` for a library OS, the console for
//! the kernel. A kernel that owned *layout* would be the thing D11's budget
//! forbids; a kernel that owns a glyph table is reading a lookup.
//!
//! Clean-room: the shapes were drawn for this project, not lifted from an
//! existing font.

#![no_std]

/// 8x8 glyph cell dimensions.
pub const FONT_W: u32 = 8;
pub const FONT_H: u32 = 8;

/// The 8x8 rows for character `c` (lowercase folds to uppercase). MSB is the
